#!/usr/bin/env python3
"""Builds docs/REPORT.md from a run_benchmarks.sh output directory (Sprint 5, M5.4).
Usage: make_report.py <campaign dir>  (Markdown on stdout)"""
import glob
import json
import os
import re
import sys

MONA_BEST_TOUR = 5757191        # best known tour (MASTER §7): gap benchmark, optimality NOT proven
MONA_BEST_BOUND = 5757084
OPTIMA = {"eil51": 426, "berlin52": 7542, "a280": 2579, "pr1002": 259045, "fl3795": 28772, "pla85900": 142382641}
PR1002_OPT = 259045

d = sys.argv[1]
meta = json.load(open(os.path.join(d, "meta.json")))
runs = []
for rj in sorted(glob.glob(os.path.join(d, "*.run.json"))):
    r = json.load(open(rj))
    rep = rj.replace(".run.json", ".json")
    r["report"] = json.load(open(rep)) if os.path.exists(rep) else None
    runs.append(r)


def fmt_int(v):
    return "-" if v is None else str(v)


def pct(v, digits=4):
    return "-" if v is None else f"{v:.{digits}f}%"


def mb(b):
    return f"{b / 1048576:.0f} MB"


def row_ctx(r):
    return f"{meta['seed']} | {r['threads']} | {meta['mem_limit_mb']}"


out = []
p = out.append
p("# APEX-TSP — Final benchmark report (Sprint 5)")
p("")
p(f"Generated by `engine/tools/run_benchmarks.sh` + `engine/tools/make_report.py` from `{d}`.")
p("")
p("| context | value |\n|---|---|")
p(f"| commit | `{meta['commit']}`{' (dirty tree)' if meta['dirty'] else ''} |")
p(f"| date | {meta['date']} |")
p(f"| hardware | {meta['cpu']}, {meta['logical_cpus']} logical CPUs visible, {meta['ram_gb']} GB RAM |")
p(f"| OS / compiler | {meta['os']} / {meta['compiler']} |")
p(f"| build | preset {meta['preset']} |")
p(f"| seed / threads / `--mem-limit-mb` | {meta['seed']} / {meta['threads']} (Band D: 1) / {meta['mem_limit_mb']} |")
p("")
p("Every row: same seed, thread count and memory ceiling as listed; one run at a time on the machine.")
p("Gaps: `certified` = (UB - LB) / UB with the engine's own LB (`lb_source`); `vs reference` = (UB - ref) / ref.")
p("")

bands = {}
for r in runs:
    bands.setdefault(r["band"], []).append(r)

# ---- Band A -------------------------------------------------------------------------------
p("## Band A — optimality proof, exact mode")
p("")
p("Pass: `OPTIMAL_PROVEN` (certificate: LB == UB, UB recomputed from the tour, verification pricing at every node) within the limit (MASTER §8.4: pr1002 <= 30 min, fl3795 <= 60 min).")
p("")
p("| instance | limit s | status | UB | LB | certified gap | known optimum | wall s | peak RAM | simplex it | verification rounds | cuts sec / blossom / comp | seed / threads / mem MB | pass |")
p("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
a_pass = True
for r in bands.get("A", []):
    rep = r["report"]
    if rep is None:
        p(f"| {r['instance']} | {r['limit_s']} | no report | | | | | | | | | | {row_ctx(r)} | **no** |")
        a_pass = False
        continue
    ok = rep["status"] == "OPTIMAL_PROVEN" and rep["wall_s"] <= r["limit_s"] + 5 and rep["ub"] == OPTIMA.get(r["instance"], rep["ub"])
    a_pass &= ok
    c = rep["cuts_by_family"]
    p(f"| {r['instance']} | {r['limit_s']} | {rep['status']} | {rep['ub']} | {fmt_int(rep['lb'])} | {pct(rep['gap_pct'])} | "
      f"{OPTIMA.get(r['instance'], '-')} | {rep['wall_s']:.1f} | {mb(rep['ram_peak_bytes'])} | {rep['iterations']} | "
      f"{rep['verification_rounds']} | {c['sec']} / {c['blossom']} / {c['component']} | {row_ctx(r)} | {'yes' if ok else '**no**'} |")
p("")
if bands.get("A"):
    p(f"Band A overall: **{'PASS' if a_pass else 'MISS'}**.")
    p("")

# ---- Band B -------------------------------------------------------------------------------
p("## Band B — usa13509, exact mode (stretch)")
p("")
if bands.get("B"):
    for r in bands["B"]:
        rep = r["report"]
        if rep:
            p(f"Actual: status {rep['status']}, UB {rep['ub']}, LB {fmt_int(rep['lb'])}, gap {pct(rep['gap_pct'])} in {rep['wall_s']:.0f} s "
              f"(target: optimality <= 24 h or gap <= 0.5% in <= 4 h); peak RAM {mb(rep['ram_peak_bytes'])}.")
else:
    p("**Deferred** (operator-visible decision, README §9): not run in this campaign. The 4 h / 24 h budget of the stretch band "
      "was not spent; Band A shows the exact mode does not yet prove fl3795 (3795 nodes) in 60 min, so usa13509 (13509 nodes) "
      "would report a gap, not a proof.")
p("")

# ---- Band C / D ---------------------------------------------------------------------------
def scalable_rows(band, title, criterion):
    p(title)
    p("")
    p(criterion)
    p("")
    p("| instance | limit s | status | UB | LB (lagrangian) | certified gap | reference | gap vs reference | wall s | peak RAM / ceiling | seed / threads / mem MB | pass |")
    p("|---|---|---|---|---|---|---|---|---|---|---|---|")
    ok_all = True
    for r in bands.get(band, []):
        rep = r["report"]
        if rep is None:
            p(f"| {r['instance']} | {r['limit_s']} | no report | | | | | | | | {row_ctx(r)} | **no** |")
            ok_all = False
            continue
        if r["instance"] == "mona-lisa100K":
            ref, ref_txt = MONA_BEST_TOUR, f"{MONA_BEST_TOUR} (best known tour)"
        else:
            ref = OPTIMA.get(r["instance"])
            ref_txt = f"{ref} (optimum)" if ref else "-"
        vs = None if ref is None else 100.0 * (rep["ub"] - ref) / ref
        limit_gap = 3.0 if band == "D" else 2.0
        gap_for_pass = vs if r["instance"] == "mona-lisa100K" else rep["gap_pct"]
        ram_ok = rep["ram_peak_bytes"] <= rep["mem_limit_mb"] * 1048576
        ok = rep["status"] == "done" and gap_for_pass is not None and gap_for_pass <= limit_gap and ram_ok \
            and rep["wall_s"] <= r["limit_s"] + 5
        ok_all &= ok
        p(f"| {r['instance']} | {r['limit_s']} | {rep['status']} | {rep['ub']} | {fmt_int(rep['lb'])} | {pct(rep['gap_pct'])} | {ref_txt} | "
          f"{pct(vs)} | {rep['wall_s']:.1f} | {mb(rep['ram_peak_bytes'])} / {rep['mem_limit_mb']} MB | {row_ctx(r)} | {'yes' if ok else '**no**'} |")
    p("")
    if bands.get(band):
        p(f"Band {band} overall: **{'PASS' if ok_all else 'MISS'}**.")
        p("")


scalable_rows("C", "## Band C — scalable mode",
              "Pass: pla85900 certified gap <= 2% and mona-lisa100K gap <= 2% **vs. the best known tour 5757191**, within 8 h, "
              "peak RAM <= ceiling. mona-lisa100K is a gap benchmark: its optimality is not proven by anyone (best bound "
              f"{MONA_BEST_BOUND}), and this report never calls a tour of it optimal.")
scalable_rows("D", "## Band D — standalone primal engine (1 thread)",
              "Pass: mona-lisa100K, single thread, <= 45 min, gap <= 3% vs. 5757191 (stretch 2%).")
for r in bands.get("D", []):
    rep = r["report"]
    if rep and r["instance"] == "mona-lisa100K":
        vs = 100.0 * (rep["ub"] - MONA_BEST_TOUR) / MONA_BEST_TOUR
        p(f"Stretch (<= 2%): **{'met' if vs <= 2 else 'not met'}** ({vs:.4f}%).")
        p("")

# ---- Band E -------------------------------------------------------------------------------
p("## Band E — native LP")
p("")


def read(name):
    f = os.path.join(d, name)
    return open(f).read() if os.path.exists(f) else None


dev, dse, highs, e2 = read("E_lp_devex.txt"), read("E_lp_dse.txt"), read("E_highs.txt"), read("E2_root_pr1002.txt")
if dev:
    def native(txt):
        rows = {}
        for m in re.finditer(r"^(\S+)\s+\d+\s+\d+\s+(\w+)\s+(\S+)\s+\S+\s+\S+\s+(\d+)\s+\d+\s+\d+\s+([\d.]+)", txt, re.M):
            rows[m.group(1).lower()] = (m.group(2), float(m.group(3)), int(m.group(4)), float(m.group(5)))
        fails = re.search(r"objective_failures=(\d+)", txt)
        return rows, int(fails.group(1)) if fails else None

    nd, nfail = native(dev)
    ns, sfail = native(dse)
    p("E1 (Sprint 1 gate): Netlib objectives within 1e-6 relative; total time <= 10x and iterations <= 3x HiGHS dual simplex "
      "without presolve, same files, 1 thread. HiGHS runs in the test environment only.")
    p("")
    p(f"Objective failures: Devex {nfail}, DSE {sfail}.")
    p("")
    netlib = ["adlittle", "25fv47", "sc205", "share2b", "grow22"]
    if highs:
        hs = {}
        for m in re.finditer(r"^(\S+)\.mps\s+simplex_nopresolve\s+\w+\s+\S+\s+(\d+)\s+([\d.]+)", highs, re.M):
            hs[m.group(1).lower()] = (int(m.group(2)), float(m.group(3)))
        p("| LP | Devex it | Devex s | DSE it | DSE s | HiGHS it | HiGHS s |")
        p("|---|---|---|---|---|---|---|")
        for k in netlib + ["stress_pr1002"]:
            a, b, h = nd.get(k), ns.get(k), hs.get(k)
            if a and b and h:
                p(f"| {k} | {a[2]} | {a[3]:.3f} | {b[2]} | {b[3]:.3f} | {h[0]} | {h[1]:.3f} |")
        tn = sum(nd[k][3] for k in netlib if k in nd)
        itn = sum(nd[k][2] for k in netlib if k in nd)
        tsd = sum(ns[k][3] for k in netlib if k in ns)
        its = sum(ns[k][2] for k in netlib if k in ns)
        th = sum(hs[k][1] for k in netlib if k in hs)
        ith = sum(hs[k][0] for k in netlib if k in hs)
        if th > 0 and ith > 0:
            ok = nfail == 0 and tn / th <= 10 and itn / ith <= 3
            p("")
            p(f"Netlib totals: Devex {tn:.3f} s / {itn} it, DSE {tsd:.3f} s / {its} it, HiGHS {th:.3f} s / {ith} it -> "
              f"Devex time {tn / th:.1f}x, iterations {itn / ith:.2f}x; DSE time {tsd / th:.1f}x, iterations {its / ith:.2f}x. "
              f"E1: **{'PASS' if ok else 'MISS'}**. Small LPs run in milliseconds, so their time ratios are timer noise.")
    else:
        p("HiGHS comparison not run in this campaign (set `HIGHS_PY`); objectives checked only.")
    p("")
    p("```")
    p(dev.strip())
    p("```")
    p("")
if e2:
    m = re.search(r"global_lb \(Farley, complete graph\) = ([\d.]+)", e2)
    if m:
        lb = float(m.group(1))
        ok = 0.97 * PR1002_OPT <= lb <= PR1002_OPT
        p(f"E2 (Sprint 2 gate): pr1002 root LB {lb:.4f} = {100 * lb / PR1002_OPT:.4f}% of the optimum {PR1002_OPT} "
          f"(target >= 97% and never above). E2: **{'PASS' if ok else 'MISS'}**.")
        p("")
p("## Context baselines")
p("")
p("LKH-3 / Concorde were not installed on the test machine: no context rows. (They would be context only, not part of the product.)")
p("")
p("## Regression (G5.5)")
p("")
p("Band A above re-runs the Sprint 3 and Sprint 4 limits with the final build. The accepted misses of G3.1 and G4.7 "
  "(pr1002 and fl3795 not proven in their limits, README §9) are compared against their Sprint 4 values in README §14.")
print("\n".join(out))
